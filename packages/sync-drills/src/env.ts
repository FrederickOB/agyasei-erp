/**
 * The FIXED dev-stack environment contract (infra/README.md). These values
 * are the documented defaults; env vars override but the drills are written
 * against this exact stack:
 *
 *   - Postgres 16 in docker on localhost:5433 (db erp / erp / erp_dev),
 *     wal_level=logical — NOT the host's Postgres 14 on 5432.
 *   - Self-hosted PowerSync service (open edition) on http://localhost:8080.
 *   - API dev server on http://localhost:3001.
 *   - ONE dev HS256 secret (DEV_JWT_SECRET, default dev-secret-change-me)
 *     shared by API-issued tokens and the PowerSync service's client_auth.
 *
 * Real secrets never live in this file (dev-only stack credentials).
 */
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const DATABASE_URL =
  process.env.DATABASE_URL ?? 'postgresql://erp:erp_dev@localhost:5433/erp';
export const DEV_JWT_SECRET = process.env.DEV_JWT_SECRET ?? 'dev-secret-change-me';
export const API_URL = process.env.API_URL ?? 'http://127.0.0.1:3001';
export const POWERSYNC_URL = process.env.POWERSYNC_URL ?? 'http://localhost:8080';

/** Where each drill device keeps its own sqlite file. Wiped per run. */
export const DRILL_DATA_DIR = fileURLToPath(new URL('../.drill-data/', import.meta.url));

export interface DevTenants {
  tenantA: { id: string; slug: string; legalName: string };
  tenantB: { id: string; slug: string; legalName: string };
}

/** Seeded tenant ids — generated by infra/scripts/bootstrap.ts, stable
 *  across stack:reset. */
export function loadDevTenants(): DevTenants {
  const path = fileURLToPath(new URL('../../../infra/dev-tenants.json', import.meta.url));
  return JSON.parse(readFileSync(path, 'utf8')) as DevTenants;
}

/** Today's business date (device-local trading day). */
export function todayBusinessDate(): string {
  return new Date().toISOString().slice(0, 10);
}
